def configure(llm_client, llm_model: str, reasoning_effort: str | None = None) -> None:
    global client, model, _effort
    client, model, _effort = llm_client, llm_model, reasoning_effort


def _clean(text: str) -> str:
    """Маха разсъжденията, ``` и въведения от рода на „Ето документа:“."""
    text = re.sub(r"<think>.*?</think>", "", text or "", flags=re.DOTALL)
    text = re.sub(r"^\s*```[a-z]*\s*$", "", text, flags=re.MULTILINE | re.IGNORECASE)
    lines = text.strip().splitlines()
    while lines and re.match(r"^\s*(ето|разбира се|с удоволствие|по-долу|готово)\b.*[:!.]?\s*$",
                             lines[0], re.IGNORECASE) and not lines[0].lstrip().startswith(("#", "|", ">>")):
        lines.pop(0)
    while lines and re.match(r"^\s*(надявам се|ако желаете|ако искате|кажете ми)\b", lines[-1], re.IGNORECASE):
        lines.pop()
    return "\n".join(lines).strip()


def compose(kind: str, request: str, slides: int = 6) -> str:
    """Текстът на документа („document“), таблицата („spreadsheet“) или презентацията
    („presentation“) по молбата на сър — в опростен markdown."""
    if client is None:
        raise RuntimeError("езиковият модел още не е готов")
    rules = {"document": DOCUMENT, "spreadsheet": SPREADSHEET,
             "presentation": PRESENTATION.format(slides=max(2, min(slides, 20)))}[kind]
    now = datetime.now()
    system = BASE.format(today=f"{clock.date_text(now)} ({now:%d.%m.%Y} г.)") + "\n\n" + rules
    reply = client.chat.completions.create(
        model=model,
        temperature=0.4,
        max_tokens=4000,
        messages=[{"role": "system", "content": system}, {"role": "user", "content": request}],
        # Без „мислене“: иначе qwen3.5 понякога оставя самия текст в разсъжденията си.
        **({"reasoning_effort": "none"} if _effort else {}),
    )
    text = _clean(reply.choices[0].message.content)
    if not text:
        raise RuntimeError("не успях да напиша текста — опитайте отново")
    return text
